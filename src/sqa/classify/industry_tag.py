"""行业标签映射（01 号文档 §5.4）：申万一级 → consumer / tech / other。

行业标签独立于风格判定（京东方=周期+科技、牧原=周期+消费是同一模式）。
词表对数据商行业字符串做子串匹配：先判"强科技/工业设备词"，再消费，最后
通用科技词——避免"软件服务/纺织机械"因宽词"服务/纺织"被判成消费。
"""
from __future__ import annotations

# 强科技/工业词优先：这些词出现时基本可确定不应归消费
_TECH_STRONG: tuple[str, ...] = (
    "机械", "机床", "设备", "仪表", "电子", "半导体", "芯片", "软件",
    "互联网", "计算机", "通信", "电信", "军工", "国防", "航天", "航空",
    "电池", "光伏", "风电", "电网",
)

_CONSUMER_KEYWORDS: tuple[str, ...] = (
    # 食品饮料
    "食品", "饮料", "白酒", "啤酒", "乳品", "乳制品", "酒类", "黄酒", "红黄酒",
    "调味", "休闲食品", "快餐",
    # 农林牧渔（养殖已被周期清单截胡为风格，标签仍归消费）
    "农业", "农牧", "种植", "种子", "林业", "渔业", "养殖", "生猪", "水产",
    "动物保健", "饲料",
    # 家用电器（"家用电器"不含"家电"子串——复合词拆分陷阱，两词都要）
    "家电", "电器", "厨卫",
    # 纺织服饰（纺织机械已被强科技词截胡）
    "纺织", "服装", "服饰", "家纺", "鞋帽",
    # 商贸零售 / 社会服务 / 美容护理
    "商贸", "零售", "百货", "超市", "连锁", "电商", "批发", "商品城",
    "旅游", "酒店", "餐饮", "免税", "景区", "教育",
    "文教", "休闲", "美容", "护理", "化妆", "日用化工",
    # 轻工制造
    "家居", "文具", "造纸", "包装", "印刷", "轻工",
)

_TECH_KEYWORDS: tuple[str, ...] = (
    # 电子（"元器件"不含"元件"子串——复合词陷阱）
    "半导体", "电子", "芯片", "元件", "元器件", "器件", "光电子", "消费电子",
    # 计算机 / 传媒 / 通信（"电信运营"不含"通信"）
    "计算机", "软件", "信息", "通信", "电信", "传媒", "游戏", "广告", "影视", "出版",
    "互联网",
    # 电力设备（新能源）
    "电力设备", "电池", "光伏", "风电", "电网",
    # 国防军工（含造船：航海装备）
    "军工", "国防", "航天", "航空", "船舶",
    # 机械设备（工程机械已被周期清单截胡为风格）
    "机械", "机床", "设备", "仪器", "仪表", "自动化", "机器人",
)


def tag_industry(industry: str) -> str:
    """行业字符串 → consumer / tech / other（强科技词 → 消费 → 通用科技词）。"""
    ind = industry or ""
    if any(kw in ind for kw in _TECH_STRONG):
        return "tech"
    if any(kw in ind for kw in _CONSUMER_KEYWORDS):
        return "consumer"
    if any(kw in ind for kw in _TECH_KEYWORDS):
        return "tech"
    return "other"
